// Target food cost as a share of the menu price, by dish type; nudged per
// menu so the margins spread out the way a real menu's do.
const TARGET = { แกง: 0.36, ต้ม: 0.34, ผัด: 0.33, ทอด: 0.35, ยำ: 0.32, นึ่ง: 0.4, พื้นบ้าน: 0.37, อบ: 0.38, ทานเล่น: 0.3, น้ำพริก: 0.3, ไข่: 0.25, คั่วกลิ้ง: 0.3, ตำ: 0.28, ข้าวจานเดียว: 0.34 };
function hash(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) h = Math.imul(h ^ str.charCodeAt(i), 16777619);
  return h >>> 0;
}
const round3 = (n) => Math.round(n * 1000) / 1000;
const round2 = (n) => Math.round(n * 100) / 100;

function recipeFor(name, price, cat) {
  if (FIXED[name]) return FIXED[name];
  const lines = [];
  const add = (ing, q) => {
    if (!ING[ing] || lines.some((l) => l[0] === ing)) return;
    lines.push([ing, q]);
  };
  // Supporting ingredients first (cost known), then size the main one to hit the target.
  const sideKey = Object.keys(SIDE).find((k) => name.includes(k)) || (cat === 'ผัด' ? 'ผัด' : cat === 'ทอด' ? 'ทอด' : cat === 'ยำ' ? 'ยำ' : cat === 'น้ำพริก' ? 'น้ำพริก' : null);
  const main = (MAIN.find(([k]) => name.includes(k)) || [null, 'ผักรวม'])[1];
  EXTRA.forEach(([k, ing, q]) => { if (name.includes(k) && ing !== main) add(ing, q); });
  (SIDE[sideKey] || [['กระเทียม', 0.01], ['น้ำปลา', 0.02]]).forEach(([ing, q]) => { if (ing !== main) add(ing, q); });
  const nudge = 0.9 + (hash(name) % 25) / 100; // 0.90 – 1.14
  const target = price * (TARGET[cat] || 0.33) * nudge;
  const sideCost = lines.reduce((s, [ing, q]) => s + q * ING[ing].price, 0);
  const unit = ING[main].price;
  const mainQty = Math.max(unit < 10 ? 1 : 0.03, (target - sideCost) / unit);
  lines.unshift([main, unit < 10 ? Math.max(1, Math.round(mainQty)) : round3(mainQty)]);
  return lines;
}

// Rows in the shape of FMH's menu_and_ingredients/recipe_table.
function recipeRows(branch = 'ร้านเกาะยอ') {
  const rows = [];
  MENUS.forEach(([posName, price, cat, fmhName], i) => {
    const menuName = fmhName || posName;
    recipeFor(posName, price, cat).forEach(([ing, q]) => {
      const p = ING[ing];
      const cost = round2(q * p.price);
      rows.push({
        branch, department: 'ครัวร้าน', menu_name: menuName, menu_code: `KY-M${String(i + 1).padStart(3, '0')}`, menu_category: cat,
        ingredient_type: 'RAW', ingredient_name: ing, ingredient_code: p.code, ingredient_category: p.cat, ingredient_qty: q,
        ingredient_uom: p.uom, yield_loss_pct: 0, cost, yield_loss_cost: 0, total_cost: cost,
      });
    });
  });
  return rows;
}

